"""MFTIK broker protocol — typed envelopes and topic names.

Protocol v2 (IF-01, F26). Every envelope carries ``pv``. The only state
this package is the authority for is that version (§3.3): a code
constant, and a receiver whose copy differs refuses the message with
``protocol_mismatch`` without parsing the payload. Intent rows, session
status, worker liveness and market data each have their own authority;
the models here are the shape those authorities publish.
"""

